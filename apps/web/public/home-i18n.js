export const HOME_LANGS = Object.keys(DICT);

export function detectHomeLang(languages = [], remembered = null) {
  if (HOME_LANGS.includes(remembered)) return remembered;
  for (const item of languages) {
    const code = String(item).slice(0, 2).toLowerCase();
    if (HOME_LANGS.includes(code)) return code;
  }
  return 'vi';
}

export function missingHomeTranslations(keys = Object.keys(DICT.vi)) {
  const missing = {};
  for (const code of HOME_LANGS) {
    const absent = keys.filter((key) => !Object.hasOwn(DICT[code], key));
    if (absent.length) missing[code] = absent;
  }
  return missing;
}

function applyHomeLang(code, root = document, vars = {}) {
  const words = DICT[code];
  const format = (value) => value.replace(/\{(\w+)\}/g, (match, key) => vars[key] ?? match);
  for (const node of root.querySelectorAll('[data-home-i18n]')) node.textContent = format(words[node.dataset.homeI18n]);
  for (const node of root.querySelectorAll('[data-home-i18n-aria]')) node.setAttribute('aria-label', words[node.dataset.homeI18nAria]);
  for (const node of root.querySelectorAll('[data-home-i18n-content]')) node.setAttribute('content', words[node.dataset.homeI18nContent]);
  root.documentElement.lang = code === 'zh' ? 'zh-Hant' : code;
}

export function initHomeI18n(root = document, storage = localStorage, languages = navigator.languages || [navigator.language], vars = {}) {
  let remembered = null;
  try { remembered = storage.getItem('thien-lang'); } catch {}
  const select = root.getElementById('homeLanguage');
  const apply = (code) => {
    select.value = code;
    applyHomeLang(code, root, vars);
  };
  apply(detectHomeLang(languages, remembered));
  select.addEventListener('change', () => {
    try { storage.setItem('thien-lang', select.value); } catch {}
    apply(select.value);
  });
}
