export const LANGS = Object.keys(DICT);
const LOCALES = { vi: 'vi-VN', en: 'en-US', zh: 'zh-TW', es: 'es-US' };
const listeners = new Set();
let current = 'vi';

export const lang = () => current;
export const locale = () => LOCALES[current];

// Dùng trong test để bảo đảm khi thêm chữ mới, cả bốn ngôn ngữ đều được cập nhật thay vì âm thầm rơi về tiếng Việt.
export function missingTranslations(keys = Object.keys(DICT.vi)) {
  const missing = {};
  for (const code of LANGS) {
    const absent = keys.filter((key) => !Object.hasOwn(DICT[code], key));
    if (absent.length) missing[code] = absent;
  }
  return missing;
}

export function t(key, vars = {}) {
  const value = DICT[current][key] ?? DICT.vi[key] ?? key;
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (match, name) => (vars[name] ?? match));
}

// Ngôn ngữ đoán từ trình duyệt khi người dùng chưa chọn.
export function guessLang() {
  for (const item of navigator.languages || [navigator.language || 'vi']) {
    const code = String(item).slice(0, 2).toLowerCase();
    if (DICT[code]) return code;
  }
  return 'vi';
}

// Chữ tĩnh trong HTML: data-i18n (nội dung), data-i18n-placeholder, data-i18n-title, data-i18n-aria.
export function applyDom(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of root.querySelectorAll('[data-i18n-title]')) node.title = t(node.dataset.i18nTitle);
  for (const node of root.querySelectorAll('[data-i18n-aria]')) node.setAttribute('aria-label', t(node.dataset.i18nAria));
  document.documentElement.lang = current === 'zh' ? 'zh-Hant' : current;
  document.title = t('page.title');
}

export function setLang(next) {
  if (!DICT[next] || next === current) return;
  current = next;
  applyDom();
  for (const listener of listeners) listener(current);
}

export function onLangChange(listener) {
  listeners.add(listener);
}
