export function photoText(language, key, vars = {}) {
  const value = PHOTO_TEXT[language]?.[key] ?? PHOTO_TEXT.vi[key] ?? key;
  return value.replace(/\{(\w+)\}/g, (match, name) => (vars[name] ?? match));
}

// Khung ngắm trong vùng w × h (điểm CSS): màn dọc 9:16 (đăng TikTok / Reels), màn ngang 16:9; nằm giữa, chạm hai cạnh.
export function photoFrame(width, height) {
  const wide = width > height;
  const ratio = wide ? 16 / 9 : 9 / 16;
  let frameWidth = width;
  let frameHeight = width / ratio;
  if (frameHeight > height) {
    frameHeight = height;
    frameWidth = height * ratio;
  }
  return { left: (width - frameWidth) / 2, top: (height - frameHeight) / 2, width: frameWidth, height: frameHeight, wide };
}
